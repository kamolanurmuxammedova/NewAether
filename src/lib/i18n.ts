export type TranslationKeys = {
  [K in keyof typeof TRANSLATIONS.ru]: string;
} & { lang: Language };

export function useTranslation(lang?: string): TranslationKeys {
  const storeLang = useUserStore((s) => s.language);
  const effective = lang || storeLang || "ru";
  const selectedLang = (
    effective.toLowerCase() === "en" ? "en" : effective.toLowerCase() === "uz" ? "uz" : "ru"
  ) as Language;
  return {
    ...TRANSLATIONS[selectedLang],
    lang: selectedLang,
  };
}

